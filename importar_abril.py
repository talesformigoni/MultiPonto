            dados_ponto = {
                "uid_residente": uid,
                "data_registro": data_str,
                "mes_referencia": mes_ref,
                "categoria": "Prática",
                "horas_computadas": total_dinamico,
                "horarios_descritos": horarios_formatados,
                "justificativa": f"Importação em lote{obs_esp}",
                "ultima_edicao": firestore.SERVER_TIMESTAMP
            }
            db.collection("pontos").document(f"{uid}_{data_str}_Prática").set(dados_ponto)
            print(f"  ✅ {data_str} salvo! ({total_dinamico}h computadas)")

