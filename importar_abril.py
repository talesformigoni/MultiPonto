def calcular_saldo_horas(entrada_str, saida_str):
    if not entrada_str or not saida_str: return 0.0
    td_entrada = datetime.strptime(entrada_str, "%H:%M")
    td_saida = datetime.strptime(saida_str, "%H:%M")
    segundos = (td_saida - td_entrada).total_seconds()
    if segundos < 0: segundos += 24 * 3600
    return round(segundos / 3600, 2)

